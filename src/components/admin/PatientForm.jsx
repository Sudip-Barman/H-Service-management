// ============================================================================
// Input Field
// ============================================================================

function InputField({
  label,
  name,
  type = "text",
  value,
  onChange,
  placeholder = "",
  required = false,
  min,
  max,
  readOnly = false,
}) {
  return (
    <div>

      <label
        htmlFor={name}
        className="mb-1.5 block text-xs font-semibold text-[#31585A] sm:text-sm"
      >
        {label}

        {required && (
          <span className="ml-1 text-red-500">
            *
          </span>
        )}
      </label>

      <input
        id={name}
        name={name}
        type={type}
        value={value ?? ""}
        onChange={onChange}
        placeholder={placeholder}
        required={required}
        min={min}
        max={max}
        readOnly={readOnly}
        className={`h-10 w-full rounded-xl border border-[#E2EFED] bg-[#FAFDFC] px-3 text-xs text-[#173F41] outline-none transition placeholder:text-[#A0B1B1] focus:border-[#08A6A0] focus:ring-2 focus:ring-[#08A6A0]/10 sm:h-11 sm:px-3.5 sm:text-sm ${
          readOnly
            ? "cursor-not-allowed bg-[#F1F7F6] text-[#527173]"
            : ""
        }`}
      />

    </div>
  );
}

// ============================================================================
// Select Field
// ============================================================================

function SelectField({
  label,
  name,
  value,
  onChange,
  options = [],
  required = false,
}) {
  return (
    <div>

      <label
        htmlFor={name}
        className="mb-1.5 block text-xs font-semibold text-[#31585A] sm:text-sm"
      >
        {label}

        {required && (
          <span className="ml-1 text-red-500">
            *
          </span>
        )}
      </label>

      <select
        id={name}
        name={name}
        value={value ?? ""}
        onChange={onChange}
        required={required}
        className="h-10 w-full rounded-xl border border-[#E2EFED] bg-[#FAFDFC] px-3 text-xs text-[#173F41] outline-none transition focus:border-[#08A6A0] focus:ring-2 focus:ring-[#08A6A0]/10 sm:h-11 sm:px-3.5 sm:text-sm"
      >
        <option value="">
          Select {label.toLowerCase()}
        </option>

        {options.map((option) => (
          <option
            key={option.value}
            value={option.value}
          >
            {option.label}
          </option>
        ))}
      </select>

    </div>
  );
}

